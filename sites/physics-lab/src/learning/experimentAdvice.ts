import { validateLinear, type LinearParams } from "../physics/linear";
import { formatNumber as f } from "../physics/units";
export function linearAdvice(p: LinearParams) {
  validateLinear(p);
  if (p.a === 0)
    return p.v0 === 0
      ? {
          kind: "rest",
          title: "Тележка остаётся на месте",
          explanation:
            "Начальная скорость и ускорение равны нулю: координата не меняется, путь не накапливается.",
          law: "x = x₀",
          next: "Задайте ненулевую скорость при a = 0 и сравните графики.",
        }
      : {
          kind: "uniform",
          title: "Равномерное движение",
          explanation:
            "Скорость не меняется, потому что ускорение равно нулю. Координата изменяется линейно, а путь растёт с постоянным темпом.",
          law: "x = x₀ + v₀t; s = |v₀|t",
          next: "Удвойте начальную скорость при том же времени. Во сколько раз изменится путь?",
        };
  const stop = -p.v0 / p.a;
  if (stop > 0 && stop < p.duration)
    return {
      kind: "turn",
      title: "Внутри опыта произойдёт разворот",
      explanation: `Через ${f(stop)} с скорость станет нулевой, затем изменит знак. Ускорение в момент остановки не исчезает. Путь продолжает расти, даже когда тележка возвращается.`,
      law: "t остановки = −v₀/a; путь = сумма модулей перемещений по участкам",
      next: "Выберите момент остановки на шкале времени. Сравните путь и перемещение до и после него.",
    };
  if (stop === p.duration)
    return {
      kind: "stop",
      title: "Остановка в конце опыта",
      explanation:
        "Ускорение направлено против начальной скорости. Скорость уменьшится до нуля точно в конце интервала. Если продлить этот процесс, начнётся движение в обратную сторону.",
      law: "v = v₀ + at",
      next: "Увеличьте длительность и посмотрите, когда путь перестанет совпадать с модулем перемещения.",
    };
  if (stop > p.duration)
    return {
      kind: "braking",
      title: "Тележка замедляется",
      explanation:
        "Скорость и ускорение имеют разные знаки. Модуль скорости уменьшается, но за выбранное время тележка ещё не остановится.",
      law: "v = v₀ + at; время остановки = −v₀/a",
      next: "Увеличьте модуль ускорения и проверьте, как изменится время остановки.",
    };
  return {
    kind: "acceleration",
    title: "Модуль скорости растёт",
    explanation:
      "Ускорение увеличивает скорость в направлении движения. При разгоне из покоя удвоение времени увеличивает путь в четыре раза, а удвоение ускорения — в два.",
    law: "Δx = v₀t + at²/2; при v₀ = 0 путь = |a|t²/2",
    next: "Оставьте ускорение прежним, измените длительность и сравните площадь под графиком скорости.",
  };
}
