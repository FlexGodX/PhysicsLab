import type { ModelId, ModelParams } from "../physics/catalog";
export function modelAdvice(
  id: ModelId,
  params: ModelParams,
  phase: number,
  manual: boolean,
): string {
  return id === "circular"
    ? params.releaseAt !== null &&
      phase * Number(params.duration) >= Number(params.releaseAt)
      ? "Удерживающая сила отключена: ускорение равно нулю. Положение меняется по прежнему вектору скорости — по касательной."
      : Number(params.speed) === 0
        ? "Скорость равна нулю: вращения нет, центростремительное ускорение равно нулю."
        : "Скорость направлена по касательной, ускорение — к центру. Удвойте скорость: ускорение вырастет в четыре раза. Удвойте радиус при той же скорости: ускорение уменьшится вдвое."
    : id === "measurements"
      ? manual
        ? "Ручная серия характеризует разброс и среднее. Истинная длина и смещение прибора неизвестны; по одним измерениям их определить нельзя. Сравните результат с независимым эталоном."
        : Number(params.bias) !== 0
          ? "Постоянное смещение не исчезнет от увеличения числа измерений. Среднее может быть точным относительно смещённого прибора, но далеко от истинной длины."
          : "Сравните n = 5 и n = 20 при том же seed. Обычно метод даёт более узкий интервал, но каждая отдельная случайная серия может вести себя иначе."
      : id === "gas"
        ? params.process === "isochoric"
          ? "Объём неизменен, поэтому работа газа равна нулю. Теплота целиком меняет внутреннюю энергию. Сравните с изобарным нагревом на ту же ΔT."
          : params.process === "isobaric"
            ? Number(params.T1) < Number(params.T0)
              ? "Газ охлаждается и сжимается при постоянном давлении: ΔU < 0, A < 0, Q < 0. Отведённая теплота включает уменьшение внутренней энергии и работу внешних сил над газом."
              : Number(params.T1) === Number(params.T0)
                ? "Начальная и конечная температуры равны. В этом изобарном процессе состояния совпадают: ΔU = A = Q = 0."
                : "При нагреве газ ещё и расширяется. Часть теплоты идёт на работу, поэтому требуется больше Q, чем при том же нагреве в жёстком сосуде."
            : "Температура и внутренняя энергия постоянны: ΔU = 0, Q = A. При сжатии работа и теплота отрицательны."
        : id === "lightClock"
          ? Number(params.beta) === 0
            ? "При β = 0 системы отсчёта совпадают. Оба тика равны, γ = 1, путь света вертикален в обеих панелях. Увеличьте β и сравните те же события."
            : "Собственное время измеряют часы, покоящиеся между двумя событиями в одном месте. В лабораторной системе свет идёт по наклонной, но его скорость тоже c. Обе панели показывают одни события."
          : params.closed
            ? Number(params.voltage) === 0
              ? "При U = 0 ток равен нулю, мощность и переданная энергия тоже нулевые. Выберите положительное напряжение, сохранив сопротивление."
              : "При удвоении U ток удваивается, а мощность увеличивается вчетверо. При удвоении R с тем же U ток и мощность уменьшаются вдвое."
            : "Цепь разомкнута: I = P = 0. График I(U) остаётся справочной характеристикой замкнутой цепи; рабочая точка открытой цепи показана отдельно.";
}
