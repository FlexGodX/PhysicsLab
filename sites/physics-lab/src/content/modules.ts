function tasks(id: ExtraUnitId, templates: Template[]): TaskVariant[] {
  return templates.flatMap((t) =>
    t.variants.map((v, i) => ({
      id: `${id}-${t.key}-${i ? "b" : "a"}`,
      version: revisions[`${id}-${t.key}-${i ? "b" : "a"}`] ? 2 : 1,
      templateId: `${id}-${t.key}`,
      kind: t.kind,
      prompt: revisions[`${id}-${t.key}-${i ? "b" : "a"}`]?.prompt ?? v[0],
      answer: v[1],
      explanation:
        revisions[`${id}-${t.key}-${i ? "b" : "a"}`]?.explanation ?? v[2],
      options: v[3],
      unit: v[4],
      critical: !!t.critical,
      outcomeIds: t.outcomes.map((o) => `${id}-${o}`),
      hints: [
        t.hint,
        t.law,
        revisions[`${id}-${t.key}-${i ? "b" : "a"}`]?.explanation ?? v[2],
      ],
      errorTag: `${id}_${t.key}`,
    })),
  );
}
function concept(
  key: string,
  variants: [Variant, Variant],
  hint: string,
  law: string,
  critical = false,
  outcomes = ["meaning"],
): Template {
  return { key, kind: "concept", variants, hint, law, critical, outcomes };
}
function units(variants: [Variant, Variant], critical = false): Template {
  return {
    key: "units",
    kind: "units",
    variants,
    hint: "Определите, какая величина требуется в вопросе.",
    law: "Единица должна соответствовать физическому смыслу величины.",
    critical,
    outcomes: ["units"],
  };
}
function calc(
  key: string,
  variants: [Variant, Variant],
  hint: string,
  law: string,
  critical = false,
): Template {
  return {
    key,
    kind: "calculation",
    variants,
    hint,
    law,
    critical,
    outcomes: ["law", "transfer"],
  };
}
function predict(
  variants: [Variant, Variant],
  hint: string,
  law: string,
  critical = false,
): Template {
  return {
    key: "predict",
    kind: "prediction",
    variants,
    hint,
    law,
    critical,
    outcomes: ["transfer", "meaning"],
  };
}
