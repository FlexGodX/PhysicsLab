export function assessmentTasks(round: number): TaskVariant[] {
  const suffix = round % 2 === 0 ? "a" : "b";
  return ["displacement", "direction", "units", "distance", "prediction"].map(
    (id) => k1Tasks.find((t) => t.id === `${id}-${suffix}`)!,
  );
}
