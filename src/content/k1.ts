function task(
  id: string,
  templateId: string,
  kind: TaskVariant["kind"],
  prompt: string,
  answer: string | number,
  options: string[] | undefined,
  unit: string | undefined,
  critical: boolean,
  outcomeIds: string[],
  explanation: string,
  hint: string,
  law: string,
  errorTag: string,
): TaskVariant {
  return {
    id,
    version: 1,
    templateId,
    kind,
    prompt,
    answer,
    options,
    unit,
    critical,
    outcomeIds,
    explanation,
    hints: [hint, law, explanation],
    errorTag,
  };
}
