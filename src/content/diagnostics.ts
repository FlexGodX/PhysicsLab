export function diagnosticResult(
  q: DiagnosticQuestion,
  answer: string | null,
  kind: "answer" | "skip" | "unknown",
) {
  return kind === "skip"
    ? "no-data"
    : kind === "unknown" || answer !== q.answer
      ? "gap"
      : "correct";
}
